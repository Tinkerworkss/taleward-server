WOERTERBUECHER: dict[str, dict[str, str]] = {"en": EN}


def sprache_von(request: Request) -> str:
    wahl = request.cookies.get(COOKIE)
    if wahl in SPRACHEN:
        return wahl
    for teil in (request.headers.get("accept-language") or "").split(","):
        code = teil.split(";")[0].strip().lower()[:2]
        if code in SPRACHEN:
            return code
    return STANDARD


def uebersetzer(sprache: str):
    buch = WOERTERBUECHER.get(sprache, {})

    def _(text: str, **werte) -> str:
        uebersetzt = buch.get(text, text)
        return uebersetzt.format(**werte) if werte else uebersetzt

    return _
